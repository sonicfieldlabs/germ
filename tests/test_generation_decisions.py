def test_retained_additive_decision_and_retry(decision_case):
    store, generated, later, body = decision_case
    result = retain(body)
    assert result["status"] == "retained"
    assert result["execution"] == "not_requested"
    assert result["quality_improvement"] == "not_established"
    assert store.get(generated["akousma_id"]) == generated
    assert store.get(later["akousma_id"]) == later
    assert retain(body)["reused"]
    changed = deepcopy(body)
    changed["workflow"]["decision"]["reason"] = "Different decision"
    with pytest.raises(ValueError, match="identity"):
        retain(changed)


@pytest.mark.parametrize(
    "case",
    [
        "hash",
        "missing",
        "listening",
        "policy",
        "execute",
        "generation",
        "receipt",
        "invented_evidence",
        "next_job",
    ],
)
def test_refuses_unbound_or_unsettled_decisions(decision_case, case):
    store, generated, later, body = decision_case
    d = body["workflow"]["decision"]
    if case == "hash":
        metadata = json.loads(storage.resolve_path(body["metadata_file"]).read_text())
        storage.resolve_path(metadata["output_audio_path"]).write_bytes(b"tampered")
    elif case == "missing":
        body["workflow"]["source_refs"][1] = "missing"
    elif case == "listening":
        d["subsequent_listenings"][0]["listening_ref"] = "invented-pass"
    elif case == "policy":
        d["policy_revision"] = "unknown"
    elif case == "execute":
        d["execution"] = "completed"
    elif case == "generation":
        d["generation_ref"] = "wrong"
    elif case == "receipt":
        metadata = json.loads(storage.resolve_path(body["metadata_file"]).read_text())
        storage.job_receipt_path(metadata["generation_job_id"]).unlink()
    elif case == "invented_evidence":
        body["output_evidence"] = {}
    else:
        d["next_job"] = {"status": "planned", "job_ref": "job:not-authorized"}
    with pytest.raises((ValueError, KeyError)):
        retain(body)
    assert store.get("ak_decision_local") is None


def test_route_and_planned_variation_do_not_submit_jobs(decision_case):
    store, generated, later, body = decision_case
    body["workflow"]["decision"].update(
        outcome="variation",
        next_job={"status": "planned", "job_ref": "job:later-owner-action"},
        stop_outcome="continue",
    )
    before = set(storage.jobs)
    response = TestClient(app).post("/akousma/generation/decision", json=body)
    assert response.status_code == 200, response.text
    assert set(storage.jobs) == before


