def test_record_audio_without_host_pass_binding_is_insufficient(decision_case):
    _, _, _, body = decision_case
    path = storage.resolve_path(body["metadata_file"])
    metadata = json.loads(path.read_text())
    metadata["extensions"].pop("germ.relisten")
    path.write_text(json.dumps(metadata))
    with pytest.raises(ValueError, match="host-retained"):
        retain(body)
